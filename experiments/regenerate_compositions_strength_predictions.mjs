/**
 * Regenerate `docs/model/compositions.json`'s `strength_predictions`
 * field from the current `docs/model/strength.json`, so the static
 * background dots in the Pareto plot agree with the live GP predictions.
 *
 * Background: each composition in compositions.json has a precomputed
 * strength prediction at days [1, 28] used to draw the static scatter
 * dots. The selected-composition CIRCLE in the Pareto plot is computed
 * LIVE from `predictStrengthCurve(currentComposition, [scatterDay], strengthParams)`.
 * If the precomputed dots disagree with the live GP (e.g., compositions.json
 * was generated by an older model), the circle won't land on the dot —
 * the user perceives a "snap" at the end of click-to-mix animations.
 *
 * Run: node experiments/regenerate_compositions_strength_predictions.mjs
 */

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

import {
  initStrengthModel,
  initWASM,
  predictStrengthCurve,
} from "../docs/gp.mjs";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

const docsRoot = resolve(__dirname, "..", "docs");
const params = JSON.parse(readFileSync(resolve(docsRoot, "model/strength.json"), "utf-8"));
const compositions = JSON.parse(
  readFileSync(resolve(docsRoot, "model/compositions.json"), "utf-8"),
);

console.log(`Initializing strength model (schema_version=${params.schema_version})…`);
initStrengthModel(params);
await initWASM(params);

// The compositions.json has strength_predictions at multiple days; we
// regenerate ALL days that exist in the file so every consumer stays
// in sync. The loaded `params` is already the deployed model.
const days = Object.keys(compositions.strength_predictions || { "1": [], "28": [] })
  .map(Number).sort((a, b) => a - b);
console.log(`Regenerating predictions for days [${days.join(", ")}] across ${compositions.compositions.length} compositions…`);

const t0 = Date.now();
const newPreds = {};
for (const d of days) newPreds[String(d)] = new Array(compositions.compositions.length);
for (let i = 0; i < compositions.compositions.length; i++) {
  const comp = compositions.compositions[i];
  const out = predictStrengthCurve(comp, days, params);
  for (let k = 0; k < days.length; k++) {
    newPreds[String(days[k])][i] = out.means[k];
  }
}
console.log(`  done in ${Date.now() - t0}ms.`);

// Diff vs old to give a sense of magnitude.
let maxAbs = 0;
let sumAbs = 0;
let n = 0;
for (const d of days) {
  const oldArr = compositions.strength_predictions[String(d)] || [];
  const newArr = newPreds[String(d)];
  for (let i = 0; i < newArr.length; i++) {
    if (typeof oldArr[i] === "number") {
      const dv = Math.abs(newArr[i] - oldArr[i]);
      if (dv > maxAbs) maxAbs = dv;
      sumAbs += dv;
      n++;
    }
  }
}
console.log(
  `Mean |Δ| = ${(sumAbs / Math.max(1, n)).toFixed(1)} psi, ` +
  `max |Δ| = ${maxAbs.toFixed(1)} psi (across ${n} predictions).`
);

// Write back, preserving everything else.
compositions.strength_predictions = newPreds;

// Recompute the pareto_mask if present. It depends on strength_predictions
// (used for the y-axis) and gwp_predictions (x-axis), so a stale
// strength_predictions invalidates the mask too. We use day=28 as the
// canonical Pareto-front reference (matches the test_data_freshness.mjs
// expectations and the explorer's default scatter day).
if (compositions.pareto_mask !== undefined) {
  const x = compositions.gwp_predictions;
  const y = compositions.strength_predictions["28"];
  if (x && y) {
    const mask = x.map((xi, i) => {
      const yi = y[i];
      for (let j = 0; j < x.length; j++) {
        if (j !== i && x[j] < xi && y[j] > yi) return false;
      }
      return true;
    });
    compositions.pareto_mask = mask;
    console.log(`  recomputed pareto_mask: ${mask.filter(Boolean).length}/${mask.length} on the front.`);
  }
}

writeFileSync(
  resolve(docsRoot, "model/compositions.json"),
  JSON.stringify(compositions),
);
console.log(`Wrote ${resolve(docsRoot, "model/compositions.json")}`);
