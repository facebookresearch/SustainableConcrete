"""Write a fixture of (input vector, expected feature outputs) pairs for
the JS↔Python feature-builder parity test.

The deployed feature set is the 7-name ``F5_ALLLOG_FEATURES`` list (see
``boxcrete.features.F5_ALLLOG_FEATURES``), but
``docs/feature_registry.mjs`` keeps a few extra builders for forward-
compat with possible future strength.json schemas. We snapshot the
union here so the JS-side parity test catches drift in either direction.

The fixture is checked into ``test/fixtures/`` and re-generated by hand
when feature builders change. The corresponding JS test
(``test/test_js_feature_parity.mjs``) reads it and asserts each builder
matches per-element with ``rtol=1e-12, atol=1e-15`` — well below any
plausible JS V8 ↔ PyTorch transcendental-function ULP delta but tight
enough to catch real divergence.
"""

from __future__ import annotations

import json
from pathlib import Path

import torch

from boxcrete.features import FEATURE_BUILDERS

REPO_ROOT = Path(__file__).resolve().parents[1]
FIXTURE_PATH = REPO_ROOT / "test" / "fixtures" / "feature_parity_fixture.json"


def _make_test_inputs() -> list[list[float]]:
    """A small but diverse battery of raw 10-dim composition vectors
    spanning the empirical training-data range. Enough to exercise the
    arithmetic + log paths without depending on the dataset CSV."""
    return [
        # [Cement, FlyAsh, Slag, Water, HRWR, Fine, Coarse, MaterialSource, Temp, Time]
        [400.0, 0.0, 0.0, 180.0, 2.0, 800.0, 1100.0, 0.0, 22.0, 28.0],
        [300.0, 100.0, 50.0, 170.0, 1.5, 750.0, 1050.0, 1.0, 20.0, 1.0],
        [200.0, 150.0, 150.0, 160.0, 3.0, 700.0, 1000.0, 0.0, 25.0, 7.0],
        # Edge: very low binder, high water
        [50.0, 0.0, 0.0, 200.0, 0.5, 600.0, 900.0, 0.0, 22.0, 28.0],
        # Edge: high HRWR
        [350.0, 50.0, 50.0, 175.0, 8.0, 800.0, 1050.0, 1.0, 22.0, 28.0],
        # Edge: tiny Time (catches log_maturity near-zero clamp)
        [400.0, 0.0, 0.0, 180.0, 2.0, 800.0, 1100.0, 0.0, 22.0, 0.5],
        # Edge: cold temperature (catches Temp + 10 < 0 -> 0 clamp)
        [400.0, 0.0, 0.0, 180.0, 2.0, 800.0, 1100.0, 0.0, -20.0, 28.0],
    ]


def main() -> int:
    inputs = _make_test_inputs()
    X = torch.tensor(inputs, dtype=torch.float64)  # (N, 10)

    # Compute the expected feature output for each registered builder.
    expected_per_feature: dict[str, list[float]] = {}
    for name, builder in FEATURE_BUILDERS.items():
        # Each builder takes (..., 10) and returns (..., 1).
        col = builder(X).flatten().tolist()
        expected_per_feature[name] = col

    fixture = {
        "schema_version": 1,
        "feature_names": sorted(FEATURE_BUILDERS.keys()),
        "inputs": inputs,
        "expected": expected_per_feature,
        "tolerances": {
            # rtol = relative; atol = absolute. Tight enough to catch
            # real bugs (any builder math change shifts outputs by
            # >> 1e-9), loose enough to absorb 1-ULP differences
            # between JS V8's Math.log and PyTorch's torch.log.
            "rtol": 1e-12,
            "atol": 1e-15,
        },
    }

    FIXTURE_PATH.parent.mkdir(parents=True, exist_ok=True)
    FIXTURE_PATH.write_text(json.dumps(fixture, indent=2) + "\n")
    print(
        f"wrote {FIXTURE_PATH} with {len(inputs)} inputs × "
        f"{len(expected_per_feature)} features"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
